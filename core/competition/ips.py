"""Investment Policy Statement draft (English, the language of international competitions) and a Portuguese summary.

Both texts are assembled from the numbers the build computed and from the team's own inputs (the case quotes are
quoted, never rewritten); nothing else is added. Estimates are marked [E], historical facts [H]. The wording is
probabilistic: :func:`english_promises` and the Portuguese guard (:mod:`core.purpose.language`) reject promise-like
phrases, and the build reports any hit. The draft is a starting point for the team, who must review it and write the
final deliverable in their own words.
"""

from __future__ import annotations

import re

from utils.br_format import num as br_num
from utils.br_format import pct as br_pct

PROMISES = (r"\bguarantee(?:d|s)?\b", r"\brisk[- ]free\b(?! rate)", r"\bno risk\b", r"\bcan(?:not|'t) lose\b",
            r"\bwill (?:earn|return|generate|make|double|beat|outperform|reach|deliver|grow)\b",
            r"\bcertain(?:ly)? to\b", r"\bsure (?:to|thing)\b", r"\bassured\b")
_PROMISE_RX = [re.compile(p, re.IGNORECASE) for p in PROMISES]

EXCLUSION_EN = {"combustiveis_fosseis": "fossil fuels (oil, gas and coal)", "tabaco": "tobacco",
                "armas": "weapons and defense", "alcool": "alcoholic beverages", "jogos": "gambling"}
EXCLUSION_PT = {"combustiveis_fosseis": "combustíveis fósseis (petróleo, gás e carvão)", "tabaco": "tabaco",
                "armas": "armas e defesa", "alcool": "bebidas alcoólicas", "jogos": "jogos de azar e apostas"}
THEME_EN = {"sustentabilidade": "sustainability", "saude": "health care", "tecnologia": "technology",
            "educacao": "education", "comunidade": "community", "familia_legado": "family legacy"}
THEME_PT = {"sustentabilidade": "sustentabilidade", "saude": "saúde", "tecnologia": "tecnologia",
            "educacao": "educação", "comunidade": "comunidade", "familia_legado": "família e legado"}
PROFILE_EN = {"conservador": "conservative", "moderado": "moderate", "arrojado": "aggressive"}
OBJECTIVE_EN = {"crescimento": "growth of capital", "renda": "income", "preservacao": "capital preservation",
                None: "growth of capital (not stated in the case; assumed)"}
OBJECTIVE_PT = {"crescimento": "crescimento do patrimônio", "renda": "renda", "preservacao": "preservação do capital",
                None: "crescimento do patrimônio (não dito no caso; hipótese)"}


def english_promises(text: str) -> list[str]:
    """Promise-like phrases in an English text ("guaranteed", "will earn", "risk-free" outside "risk-free rate")."""
    return [m.group(0) for rx in _PROMISE_RX for m in rx.finditer(text)]


def money_en(x: float | None, ccy: str) -> str:
    if x is None:
        return "n/a"
    sym = {"USD": "$", "BRL": "R$ ", "EUR": "€"}.get(ccy, ccy + " ")
    return f"{'-' if x < 0 else ''}{sym}{abs(x):,.0f}"


def money_pt(x: float | None, ccy: str) -> str:
    if x is None:
        return "n/d"
    sym = {"USD": "US$", "BRL": "R$", "EUR": "€"}.get(ccy, ccy)
    return f"{sym} {br_num(x, 0)}"


def price_en(x: float, ccy: str) -> str:
    sym = {"USD": "$", "BRL": "R$ ", "EUR": "€"}.get(ccy, ccy + " ")
    return f"{sym}{x:,.2f}"


def pct_en(x: float | None, d: int = 1) -> str:
    return "n/a" if x is None else f"{x * 100:.{d}f}%"


def _q(c: dict[str, str], key: str) -> str:
    """The case's own words for an item, quoted (empty when the team typed it without a quote)."""
    t = (c.get(key) or "").strip()
    return f' (case: "{t}")' if t else ""


def ips_english(x: dict[str, object]) -> str:
    """Investment Policy Statement draft from the build context ``x`` (see ``core.competition.build``)."""
    c: dict = x["cliente"]  # type: ignore[assignment]
    m: dict = x["metricas"]  # type: ignore[assignment]
    ccy = str(x["moeda"])
    quotes = c.get("citacoes") or {}
    who = c.get("nome") or "the client described in the case"
    L: list[str] = []
    L.append("INVESTMENT POLICY STATEMENT — DRAFT")
    L.append(f"Client: {who} | Competition: {x['competicao'] or 'n/a'} | Prepared on {x['data']}")
    L.append("Draft generated by a research tool from the team's inputs and public market data. Review every number "
             "and rewrite it in the team's own words before submitting. Estimates [E] are probabilistic; historical "
             "figures [H] may not repeat. This is not investment advice.")
    L.append("")
    L.append("1. CLIENT PROFILE")
    if c.get("idade"):
        L.append(f"- Age: {c['idade']}{_q(quotes, 'idade')}")
    if c.get("patrimonio"):
        L.append(f"- Investable assets today: {money_en(c['patrimonio'], c['moeda_caso'])}{_q(quotes, 'patrimonio_cliente')}")
    if c.get("meta"):
        L.append(f"- Goal: {money_en(c['meta'], c['moeda_caso'])} in {c['horizonte']:g} years"
                 f"{_q(quotes, 'valor_alvo_cliente')}")
    if c.get("aporte_anual"):
        L.append(f"- Contributions: {money_en(c['aporte_anual'], c['moeda_caso'])} per year"
                 f"{_q(quotes, 'aporte_anual_cliente')}")
    if c.get("retirada_anual"):
        L.append(f"- Withdrawals / spending needs: {money_en(c['retirada_anual'], c['moeda_caso'])} per year"
                 f"{_q(quotes, 'retirada_anual_cliente')} (not simulated by the tool; they reduce the money left to grow)")
    for g in c.get("metas_intermediarias") or []:
        L.append(f"- Intermediate goal: {g}")
    L.append(f"- Time horizon: {c['horizonte']:g} years{_q(quotes, 'horizonte_anos')}")
    L.append("")
    L.append("2. RETURN OBJECTIVE")
    L.append(f"- Primary objective: {OBJECTIVE_EN.get(c.get('objetivo'), OBJECTIVE_EN[None])}"
             f"{_q(quotes, 'objetivo_tipo')}")
    L.append(f"- How the goal was set for the analysis: {x['meta_como_en']}")
    if m.get("cagr_necessario") is not None:
        L.append(f"- Annual return needed to reach it: {pct_en(m['cagr_necessario'])}")
    L.append(f"- Expected annual return of the proposed portfolio [E]: {pct_en(m.get('retorno_E'))} (an estimate with "
             f"a wide margin of error: one standard error is about {pct_en(m.get('erro_padrao_retorno'))} a year)")
    if m.get("p_meta") is not None:
        lo, hi = m.get("ic95") or (None, None)
        L.append(f"- Probability of reaching the goal [E]: {pct_en(m['p_meta'], 0)} (Monte Carlo 95% interval "
                 f"{pct_en(lo, 0)} to {pct_en(hi, 0)}); in the pessimistic simulated scenario (10th percentile) the "
                 f"portfolio ends at {money_en(m.get('p10_final'), ccy)} on the competition's capital")
    L.append("")
    L.append("3. RISK TOLERANCE")
    L.append(f"- Willingness: {PROFILE_EN[c['perfil']]}{_q(quotes, 'perfil_risco')}")
    if c.get("tolerancia_perda"):
        L.append(f"- Largest loss the client accepts: {pct_en(c['tolerancia_perda'], 0)}{_q(quotes, 'tolerancia_perda')}"
                 f" -> volatility ceiling {pct_en(m.get('teto_vol'))} a year (rule: maximum drawdowns of diversified "
                 "portfolios are usually 2 to 3 times their annual volatility)")
    L.append(f"- Ability: {c['horizonte']:g}-year horizon"
             + (f"; up to {pct_en(c['liquidez'], 0)} of the money may be needed within 12 months" if c.get("liquidez")
                else "") + ".")
    L.append(f"- Policy: {PROFILE_EN[x['perfil_final']]} profile; expected volatility [E] {pct_en(m.get('vol_E'))} a year; "
             f"largest historical fall of these weights [H] {pct_en(m.get('drawdown_H'))}")
    L.append("")
    L.append("4. CONSTRAINTS")
    L.append(f"- Time horizon: {c['horizonte']:g} years.")
    L.append("- Liquidity: " + (f"keep about {pct_en(c['liquidez'], 0)} in short-term Treasury ETFs or cash."
                                if c.get("liquidez") else "no short-term need stated in the case."))
    L.append("- Competition rules (legal/regulatory): " + "; ".join(x["regras_en"]) + ".")  # type: ignore[arg-type]
    L.append("- Taxes: not modelled (simulated competition account).")
    unique = []
    if c.get("exclusoes"):
        unique.append("excludes " + ", ".join(EXCLUSION_EN[k] for k in c["exclusoes"]) + _q(quotes, "exclusoes"))
    if c.get("temas"):
        unique.append("values and interests: " + ", ".join(THEME_EN[k] for k in c["temas"]) + _q(quotes, "temas"))
    if c.get("observacoes"):
        unique.append(str(c["observacoes"]))
    L.append("- Unique circumstances: " + ("; ".join(unique) if unique else "none stated") + ".")
    L.append("")
    L.append("5. STRATEGIC ASSET ALLOCATION")
    for row in x["alocacao"]:  # type: ignore[union-attr]
        L.append(f"- {row['classe_en']}: {pct_en(row['peso'])}")
    L.append(f"Rationale: the mix follows the {PROFILE_EN[x['perfil_final']]} profile, the {c['horizonte']:g}-year "
             "horizon and the objective, within the competition rules: " + "; ".join(x["porque_alocacao_en"]) + ".")  # type: ignore[arg-type]
    L.append("")
    L.append("6. SECURITY SELECTION AND PORTFOLIO CONSTRUCTION")
    L.append(f"- Universe: {x['universo_en']}")
    L.append(f"- Construction: {x['estrategia_en']}")
    L.append(f"- Orders: whole shares at the last close ({x['data_precos']}); {len(x['posicoes'])} positions, "  # type: ignore[arg-type]
             f"{money_en(x['investido'], ccy)} invested and {money_en(x['caixa'], ccy)} left in cash.")
    L.append("")
    L.append("   Ticker   Shares        Price         Value   Weight  Role")
    for p in x["posicoes"]:  # type: ignore[union-attr]
        L.append(f"   {p['ticker']:<8}{p['quantidade']:>7,.0f}{price_en(p['preco'], ccy):>13}"
                 f"{money_en(p['valor'], ccy):>14}{pct_en(p['peso']):>9}  {p['papel_en']}")
    L.append("")
    L.append("7. RISK MANAGEMENT")
    L.append(f"- Diversification: {m.get('n')} positions behaving like about {m.get('enb', 0):.1f} independent bets "
             f"(effective number of bets by risk); largest position {m.get('maior_ticker')} at "
             f"{pct_en(m.get('maior_peso'))}.")
    if m.get("pior_janela_H") is not None:
        L.append(f"- Stress: the worst {x['janela']['dias']}-trading-day window in the data for these weights [H] was "  # type: ignore[index]
                 f"{pct_en(m['pior_janela_H'])} ({m.get('pior_janela_datas_en')}).")
    j: dict = x["janela"]  # type: ignore[assignment]
    if j.get("p50") is not None:
        L.append(f"- Until the end of trading ({j['fim_en']}, {j['dias']} trading days) [E]: central 80% range "
                 f"{money_en(j['p10'], ccy)} to {money_en(j['p90'], ccy)} (median {money_en(j['p50'], ccy)}); "
                 f"probability of a loss larger than 10%: {pct_en(j['p_perda_10'], 0)}.")
    L.append("")
    L.append("8. MONITORING AND REBALANCING (suggested rules; adapt them to the team's strategy)")
    L.append("- Review weights weekly during the competition; rebalance a position that drifts more than 5 percentage "
             "points from its target or breaks a rule (for example, a rally that takes it above the position limit).")
    if x.get("max_operacoes"):
        L.append(f"- The initial purchase uses {len(x['posicoes'])} of the {x['max_operacoes']} trades allowed; keep "  # type: ignore[arg-type]
                 "the rest for rebalancing and for replacing holdings.")
    L.append("- Re-examine each company's thesis after earnings releases and replace a holding when the reason it was "
             "bought no longer holds.")
    return "\n".join(L)


def summary_pt(x: dict[str, object]) -> str:
    """Portuguese summary of the same facts, for the team."""
    c: dict = x["cliente"]  # type: ignore[assignment]
    m: dict = x["metricas"]  # type: ignore[assignment]
    j: dict = x["janela"]  # type: ignore[assignment]
    ccy = str(x["moeda"])
    parts = [(f"Carteira para {c.get('nome') or 'o cliente'}: perfil {x['perfil_final']}, horizonte de "
             f"{br_num(c['horizonte'], 0) if float(c['horizonte']).is_integer() else br_num(c['horizonte'], 1)} anos, "
             f"objetivo de {OBJECTIVE_PT.get(c.get('objetivo'), OBJECTIVE_PT[None])}.")]
    parts.append(f"São {len(x['posicoes'])} posições compradas em ações inteiras com {money_pt(x['capital'], ccy)}: "  # type: ignore[arg-type]
                 f"{money_pt(x['investido'], ccy)} investidos e {money_pt(x['caixa'], ccy)} em caixa.")
    parts.append("Divisão: " + "; ".join(f"{row['classe_pt']} {br_pct(row['peso'])}" for row in x["alocacao"]) + ".")  # type: ignore[union-attr]
    parts.append(f"Retorno esperado [E] de {br_pct(m.get('retorno_E'))} ao ano e volatilidade [E] de "
                 f"{br_pct(m.get('vol_E'))}; a maior queda destes pesos no histórico [H] foi de {br_pct(m.get('drawdown_H'))}.")
    if m.get("p_meta") is not None:
        parts.append(f"Chance estimada de atingir o objetivo [E]: {br_pct(m['p_meta'], 0)} ({x['meta_como_pt']}).")
    if j.get("p50") is not None:
        parts.append(f"Até o fim das negociações ({j['fim']}), 80% dos cenários simulados [E] ficam entre "
                     f"{money_pt(j['p10'], ccy)} e {money_pt(j['p90'], ccy)}; chance de perder mais de 10%: "
                     f"{br_pct(j['p_perda_10'], 0)}.")
    if c.get("exclusoes"):
        parts.append("Fica de fora, como o cliente pediu: " + ", ".join(EXCLUSION_PT[k] for k in c["exclusoes"]) + ".")
    if c.get("temas"):
        parts.append("Inclinação para os valores do cliente: " + ", ".join(THEME_PT[k] for k in c["temas"])
                     + " (sem passar dos limites de risco).")
    parts.append("Estimativas não são promessas: o resultado real pode ficar fora dessas faixas.")
    return " ".join(parts)
